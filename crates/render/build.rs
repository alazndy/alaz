//! Embeds the repository's `assets/` folder into the binary: every .vox, .glb, .png and .toml under it becomes an
//! `include_bytes!` entry, so a shipped game needs no files beside it. With no assets the table is empty.
use std::fmt::Write;
use std::path::{Path, PathBuf};

fn walk(dir: &Path, root: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    let mut entries: Vec<_> = rd.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            walk(&p, root, out);
        } else if let Some(ext) = p.extension().and_then(|e| e.to_str())
            && matches!(ext.to_ascii_lowercase().as_str(), "vox" | "glb" | "png" | "toml") {
                let rel = p.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/");
                out.push((rel, p));
            }
    }
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("../../assets");
    println!("cargo:rerun-if-changed={}", root.display());
    println!("cargo:rerun-if-changed=build.rs");
    let mut files = Vec::new();
    walk(&root, &root, &mut files);
    let mut src = String::from("/// (path under assets/, bytes), generated by build.rs\npub static EMBEDDED: &[(&str, &[u8])] = &[\n");
    for (rel, p) in &files {
        let abs = p.canonicalize().unwrap_or_else(|_| p.clone());
        writeln!(src, "    ({:?}, include_bytes!({:?})),", rel, abs.to_string_lossy()).unwrap();
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("embedded.rs");
    std::fs::write(out, src).unwrap();
}
